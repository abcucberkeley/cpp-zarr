#!/usr/bin/env python3
"""Compiles src/gpu/kernels.cu to PTX for compute_70 (Volta) with NVRTC and writes it to
src/gpu/kernels_ptx.h, which the library embeds: the CUDA driver compiles the PTX for whatever
GPU it runs on (Volta and every later one), so building cpp-zarr needs no CUDA compiler.

Run it after changing kernels.cu, with a CUDA 12 NVRTC (CUDA 13 no longer compiles for Volta):
    python tools/gen_gpu_ptx.py [path to libnvrtc.so.12]
Without a path it looks for the nvidia-cuda-nvrtc-cu12 pip package, then the system's libnvrtc."""
import ctypes, glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src', 'gpu', 'kernels.cu')
OUT = os.path.join(HERE, '..', 'src', 'gpu', 'kernels_ptx.h')


def find_nvrtc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    try:
        import nvidia.cuda_nvrtc as m
        for base in m.__path__:
            for f in sorted(glob.glob(os.path.join(base, 'lib', 'libnvrtc.so.12*'))):
                if 'builtins' not in f and 'alt' not in f:
                    return f
    except ImportError:
        pass
    return 'libnvrtc.so.12'


def main():
    lib = ctypes.CDLL(find_nvrtc())
    major, minor = ctypes.c_int(), ctypes.c_int()
    lib.nvrtcVersion(ctypes.byref(major), ctypes.byref(minor))
    src = open(SRC).read()
    prog = ctypes.c_void_p()
    if lib.nvrtcCreateProgram(ctypes.byref(prog), src.encode(), b'kernels.cu', 0, None, None):
        sys.exit('nvrtcCreateProgram failed')
    opts = [b'--gpu-architecture=compute_70', b'--std=c++11', b'-default-device']
    res = lib.nvrtcCompileProgram(prog, len(opts), (ctypes.c_char_p * len(opts))(*opts))
    n = ctypes.c_size_t()
    lib.nvrtcGetProgramLogSize(prog, ctypes.byref(n))
    log = ctypes.create_string_buffer(n.value)
    lib.nvrtcGetProgramLog(prog, log)
    if res:
        sys.exit('nvrtc: ' + log.value.decode())
    lib.nvrtcGetPTXSize(prog, ctypes.byref(n))
    buf = ctypes.create_string_buffer(n.value)
    lib.nvrtcGetPTX(prog, buf)
    ptx = buf.value.decode()
    # The PTX is marked as ISA 7.0 (CUDA 11.0) instead of the version this NVRTC writes, so that
    # drivers back to 450 compile it: the kernels use nothing newer, and a driver rejects
    # instructions a PTX version does not have when it compiles them (the library reports it)
    import re
    ptx, k = re.subn(r'^\.version \d+\.\d+$', '.version 7.0', ptx, count=1, flags=re.M)
    if k != 1:
        sys.exit('no .version line in the PTX')
    # (string literals of at most 4000 characters: compilers limit their length)
    lines, pieces, cur = ptx.splitlines(keepends=True), [], ''
    for line in lines:
        if len(cur) + len(line) > 4000:
            pieces.append(cur)
            cur = ''
        cur += line
    pieces.append(cur)
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/gen_gpu_ptx.py from kernels.cu (NVRTC %d.%d, compute_70, PTX ISA 7.0): do not edit\n'
                % (major.value, minor.value))
        f.write('#ifndef CPPZARR_KERNELS_PTX_H\n#define CPPZARR_KERNELS_PTX_H\n')
        f.write('static const char* const cppzarrKernelsPtx[] = {\n')
        for p in pieces:
            f.write('R"CZPTX(' + p + ')CZPTX",\n')
        f.write('};\n#endif\n')
    print(f'{OUT}: {len(ptx)} bytes of PTX in {len(pieces)} pieces (NVRTC {major.value}.{minor.value})')


if __name__ == '__main__':
    main()
